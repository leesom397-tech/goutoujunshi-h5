import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

const root = fileURLToPath(new URL("../knowledge", import.meta.url));
const output = fileURLToPath(new URL("../lib/knowledge.generated.json", import.meta.url));

function collect(directory, prefix = "") {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const relative = path.posix.join(prefix, entry.name);
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) return collect(absolute, relative);
    if (!entry.isFile() || !entry.name.endsWith(".md")) return [];
    const content = readFileSync(absolute, "utf8");
    return [{ id: relative, title: entry.name.replace(/\.md$/, ""), content }];
  });
}

const documents = collect(root).sort((a, b) => a.id.localeCompare(b.id, "zh-CN"));
if (documents.length < 44 || !documents.some((document) => document.id === "SKILL.md")) {
  throw new Error(`Expected the core skill plus at least 43 reference documents; found ${documents.length}.`);
}
writeFileSync(output, JSON.stringify(documents), "utf8");
const hanCount = (content) => (content.match(/\p{Script=Han}/gu) || []).length;
const labels = [
  ["实战话术编排器", "回复表达与后续应对"],
  ["关系投入失衡", "双向投入与去留判断"],
  ["09-", "网聊信号与误读"],
  ["03-", "依恋与情绪调节"],
  ["07-", "争吵沟通与关系修复"],
  ["15-", "分手、背叛与修复"],
  ["02-", "亲密关系与长期适配"],
  ["06-", "吸引、约会与主动推进"],
  ["17-", "关系安全与求助"],
];
const publicDocuments = documents.filter((document) => document.id !== "SKILL.md").map((document) => ({
  id: document.id,
  title: document.title.replace(/^\d+-/, ""),
  label: labels.find(([prefix]) => document.title.startsWith(prefix))?.[1] || document.title.replace(/^\d+-/, "").split("：")[0],
  anchor: "guide-" + createHash("sha256").update(document.id).digest("hex").slice(0, 12),
  category: document.id.startsWith("references/knowledge/") ? "knowledge" : "practical",
  hanCharacters: hanCount(document.content),
}));
const manifest = {
  totalDocuments: documents.length,
  referenceDocuments: publicDocuments.length,
  knowledgeDocuments: publicDocuments.filter((document) => document.category === "knowledge").length,
  practicalDocuments: publicDocuments.filter((document) => document.category === "practical").length,
  hanCharacters: documents.reduce((total, document) => total + hanCount(document.content), 0),
  documents: publicDocuments,
};
writeFileSync(fileURLToPath(new URL("../lib/knowledge-manifest.generated.json", import.meta.url)), JSON.stringify(manifest), "utf8");
// The Mini Program cannot import files outside miniprogramRoot. Generate its
// public counters from the same manifest, excluding the internal SKILL.md.
const miniappStats = {
  sourceCount: manifest.referenceDocuments,
  knowledgeCount: manifest.knowledgeDocuments,
  practicalCount: manifest.practicalDocuments,
  hanCharacters: publicDocuments.reduce((total, document) => total + document.hanCharacters, 0),
};
writeFileSync(fileURLToPath(new URL("../miniapp/lib/knowledge-stats.js", import.meta.url)),
  "// Generated by scripts/build-knowledge.mjs. Do not edit manually.\nmodule.exports = " + JSON.stringify(miniappStats) + ";\n", "utf8");
console.log(`Bundled ${documents.length} 狗头军师 documents.`);
