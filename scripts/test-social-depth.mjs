import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import ts from 'typescript';
const cache=new Map();
function load(file){ const path=resolve(file); if(cache.has(path))return cache.get(path); const out={};cache.set(path,out); const source=ts.transpileModule(readFileSync(path,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText; new Function('exports','require',source)(out,id=>load((id.startsWith('@/')?id.slice(2):resolve(dirname(path),id))+'.ts'));return out; }
const {relationshipFit}=load('lib/relationship-fit.ts');
const row=result=>result.fit.find(x=>x.field==='relationshipStatus');
assert.equal(row(relationshipFit({}, {relationshipStatus:'认真谈场恋爱，合适可以考虑结婚'})).status,'有线索','a clearly stated goal is not erased by a missing self profile');
assert.match(row(relationshipFit({}, {relationshipStatus:'认真谈场恋爱，合适可以考虑结婚'})).conclusion,/认真谈场恋爱/);
assert.equal(row(relationshipFit({goals:'认真发展长期关系'},{relationshipStatus:'认真恋爱，合适可以考虑结婚'})).status,'匹配');
assert.equal(relationshipFit({},{},{},{sameCity:true}).fit[1].status,'有线索');
assert.match(relationshipFit({},{},{},{sameCity:true}).fit[1].evidence,/用户确认/);
assert.equal(relationshipFit({},{}).fit[1].status,'待了解','never assume the user and the profile are local');
const {publicMomentsCase:demo,publicSocialCase:social}=load('data/public-social-cases.ts');
const {cleanMomentsReport}=load('lib/moments-report.ts');
assert.equal(demo.moments.posts.length,8);
assert.equal(demo.fit.length,6);
assert.ok(demo.fit.every(x=>x.score===null),'visible clues are not fabricated scores');
assert.ok(demo.moments.hypotheses.length>=3);
assert.ok(demo.moments.compositionReading.conclusion&&demo.moments.timelineReading.conclusion);
assert.ok(demo.moments.photoClues.every(x=>x.inference&&x.alternative&&x.verify));
assert.deepEqual(cleanMomentsReport(demo.moments),demo.moments,'archive roundtrip preserves photos and conclusions');
assert.ok(social.profileBasics.some(x=>x.field==='relationshipStatus'));
assert.ok(social.photoClues.every(x=>x.inference&&x.alternative));
const {momentsFit}=load('lib/moments-fit.ts');
assert.equal(momentsFit({},{}).fit.length,0,'empty material cannot manufacture a full profile');
assert.ok(momentsFit({},demo.moments).fit.every(x=>x.evidence&&x.conclusion),'legacy moments receive traceable interpretations');
console.log('PASS social depth: known goals/city, complete fictional cases, material-led dimensions, photo/archive preservation');
