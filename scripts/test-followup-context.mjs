import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const navigations = [];
let failNavigation = false;
const wx = { navigateTo(options) { navigations.push(options.url); if (failNavigation) options.fail(); else options.success(); } };
const module = { exports: {} };
new Function('module', 'wx', readFileSync('miniapp/lib/followup-context.js', 'utf8'))(module, wx);
const helper = module.exports;
const subjectId = '11111111-1111-4111-8111-111111111111';
await assert.rejects(helper.openReportFollowup({ summary: 'report', token: '' }));
await helper.openReportFollowup({ subjectId, token: 'identity-A', title: '聊天分析', summary: '可能想继续了解。依据：周日见。', question: '为什么这样判断？' });
const query = new URL('https://local' + navigations.at(-1)).searchParams;
assert.equal(query.get('subjectId'), subjectId);
const context = helper.takeReportFollowup(query.get('contextKey'));
assert.equal(context.sessionToken, 'identity-A');
assert.equal(context.question, '为什么这样判断？');
assert.equal(helper.takeReportFollowup(query.get('contextKey')), null, 'handoff is single-use');
const history = helper.reportHistory(context, Array.from({ length: 8 }, (_, i) => ({ role: i % 2 ? 'assistant' : 'user', content: String(i) })));
assert.ok(history[0].content.includes('并非已确认事实'));
assert.equal(history.at(-1).content, '7');
assert.ok(history.length <= 6);
const body = helper.fitHistoryToRequest({ mode: 'conversation', self: '中'.repeat(1500), history: helper.reportHistory({ summary: '证'.repeat(1050) }, Array.from({ length: 6 }, () => ({ role: 'user', content: '史'.repeat(600) }))), subjectId, confirmed: true });
assert.ok(Buffer.byteLength(JSON.stringify(body)) <= 11000, 'Chinese context stays under API limit');
assert.equal(body.self.length, 1500, 'never silently trim the current question');
failNavigation = true;
await assert.rejects(helper.openReportFollowup({ token: 'identity-A', summary: 's' }), /暂时未能打开/);
assert.equal(helper.takeReportFollowup(new URL('https://local' + navigations.at(-1)).searchParams.get('contextKey')), null);

let definition;
const calls = [];
const api = { newId: async () => subjectId, request: async (...args) => { calls.push(args); return { possibleIntent: '这是一种可能', evidence: '依据', nextStep: '先接话', replies: [] }; }, session: async () => ({ token: 'identity-A', state: { subjects: [{ id: subjectId, label: '甲' }] } }) };
let storedToken = 'identity-A';
const native = { getStorageSync: () => ({ token: storedToken }), removeStorageSync() {}, pageScrollTo() {} };
function chat() {
  new Function('Page', 'require', 'wx', readFileSync('miniapp/pages/chat/index.js', 'utf8'))(value => { definition = value; }, name => name.endsWith('/api') ? api : helper, native);
  return { ...definition, data: structuredClone(definition.data), setData(update, done) { Object.assign(this.data, update); done?.(); } };
}
failNavigation = false;
await helper.openReportFollowup({ subjectId, token: 'identity-A', title: '聊天分析', summary: '对方原话：下次聊。推测：未必是在拒绝。' });
const page = chat();
page.onLoad({ contextKey: new URL('https://local' + navigations.at(-1)).searchParams.get('contextKey'), subjectId });
assert.equal(page.data.agreed, false);
assert.equal(calls.length, 0, 'opening a report never sends a paid question');
await page.refresh();
assert.equal(page.data.personIndex, 1);
page.setData({ self: '为什么不是拒绝？', agreed: true });
await page.analyze();
assert.equal(calls.length, 1);
assert.equal(calls[0][2].subjectId, subjectId);
assert.ok(calls[0][2].history[0].content.includes('下次聊'));
page.personChange({ detail: { value: '0' } });
assert.equal(page.data.followupTitle, '');
assert.equal(page._followupContext, null, 'changing a person must not carry another report');
assert.equal(page.data.agreed, false);
page._followupContext = { ...context, expiresAt: Date.now() - 1 };
page.setData({ self: '再聊聊', agreed: true, personIndex: 1 });
await page.analyze();
assert.equal(calls.length, 1, 'expired context never reaches the paid API');
assert.match(page.data.error, /失效/);
page._followupContext = { ...context, expiresAt: Date.now() + 60000 };
storedToken = 'identity-B';
page.setData({ self: '这个呢', agreed: true });
await page.analyze();
assert.equal(calls.length, 1, 'switching stored identity blocks an old report even if page token is unchanged');
assert.equal(page._followupContext, null);
const secondPage = chat();
storedToken = 'identity-A';
secondPage._followupContext = { ...context, expiresAt: Date.now() + 60000 };
secondPage.setData({ phase: 'ready', token: 'identity-A', people: [{ id: subjectId, label: '甲' }], personIndex: 0, agreed: true, self: '接着说吧' });
let finishRequest;
api.request = () => new Promise(resolve => { finishRequest = resolve; });
const inFlight = secondPage.analyze();
await new Promise(resolve => setImmediate(resolve));
assert.equal(typeof finishRequest, 'function');
storedToken = 'identity-B';
secondPage.onShow();
finishRequest({ possibleIntent: '旧身份私密回答', evidence: '旧资料', nextStep: '旧建议', replies: [] });
await inFlight;
assert.deepEqual(secondPage.data.messages, [], 'an old in-flight response must never appear in the new identity');
console.log('followup context: PASS (scoped identity/person, consent, bounded request, no automatic spend)');
