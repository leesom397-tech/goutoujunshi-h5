import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
let definition;
const navigation = [];
const api = { setCurrentSubject() {} };
const wx = { navigateTo({ url }) { navigation.push(url); }, pageScrollTo() {} };
new Function("require", "Page", "wx", readFileSync("miniapp/pages/archive/index.js", "utf8"))(name => name.endsWith("/api") ? api : { drawRadar() {}, drawTrend() {} }, value => { definition = value; }, wx);
const page = { ...definition, data: structuredClone(definition.data), setData(value, callback) { Object.assign(this.data, value); callback?.(); } };
page.onLoad({ subjectId: "A" });
page.apply({ enabled: true, subjects: [{ id: "A", label: "人物甲" }, { id: "B", label: "人物乙" }], facts: [{ id: "a", subjectId: "A", status: "pending", value: "甲的资料" }, { id: "b", subjectId: "B", status: "pending", value: "乙的资料" }, { id: "self", subjectId: null, status: "pending", value: "本人的资料" }] });
assert.deepEqual(page.data.pendingFacts.map(item => item.id), ["a"]);
let payload;
page.action = async value => { payload = value; };
page.confirmAll();
assert.deepEqual(payload.ids, ["a"], "detail confirmation must not include another person");
page.switchDetailSection({ currentTarget: { dataset: { section: "trend" } } });
assert.equal(page.data.detailSection, "trend");
page.switchDetailSection({ currentTarget: { dataset: { section: "invalid" } } });
assert.equal(page.data.detailSection, "trend");
page.openSubjectDetail({ currentTarget: { dataset: { id: "B" } } });
assert.equal(navigation.at(-1), "/pages/archive/index?subjectId=B");
page.switchArchiveTab({ currentTarget: { dataset: { tab: "self" } } });
assert.equal(page.data.selectedId, "");
assert.deepEqual(page.data.pendingFacts.map(item => item.id), ["self"]);
let reportDefinition, clipboard;
new Function("require", "Page", "wx", readFileSync("miniapp/pages/report/index.js", "utf8"))(() => api, value => { reportDefinition = value; }, { setClipboardData(value) { clipboard = value.data; } });
const report = { ...reportDefinition, data: { ...reportDefinition.data, report: { replies: [{ text: "周六下午方便吗？" }] } }, setData(value) { Object.assign(this.data, value); } };
assert.equal(report.data.showLines, true);
report.toggleLines();
assert.equal(report.data.showLines, false);
report.copyReply({ currentTarget: { dataset: { index: 0 } } });
assert.equal(clipboard, "周六下午方便吗？");
const home = readFileSync("miniapp/pages/home/index.wxml", "utf8");
assert.ok(home.indexOf('class="knowledge-cover"') < home.indexOf('data-entry="quick"'), "knowledge basis should lead the analysis entry");
assert.ok(home.indexOf('data-entry="quick"') < home.indexOf('data-entry="archive"'), "analysis actions should remain ahead of follow-up navigation");
assert.equal((home.match(/data-entry="archive"/g) || []).length, 1);
assert.ok(home.includes('data-entry="self"'));
const archiveMarkup = readFileSync("miniapp/pages/archive/index.wxml", "utf8");
assert.ok(archiveMarkup.includes("selectedSignal.score != null"), "missing scores must not render undefined/100");
console.log("PASS: detail navigation, scoped confirmation, self separation, section guards, report disclosure, reply copy and home entry ownership");
let socialDefinition;
new Function("require", "Page", "wx", readFileSync("miniapp/pages/social-profile/index.js", "utf8"))(() => ({}), value => { socialDefinition = value; }, {});
const social = { ...socialDefinition, data: { result: { hypotheses: [{ title: "推测甲", possibility: "可能甲", evidence: "原话甲" }, { title: "推测乙", possibility: "可能乙", evidence: "原话乙" }] } }, setData(value) { Object.assign(this.data, value); } };
social.toggleHypothesis({ currentTarget: { dataset: { index: 0 } } });
assert.equal(social.data.result.hypotheses[0].expanded, true);
assert.equal(social.data.result.hypotheses[1].expanded, undefined);
assert.equal(social.data.result.hypotheses[0].possibility, "可能甲");
social.toggleHypothesis({ currentTarget: { dataset: { index: 0 } } });
assert.equal(social.data.result.hypotheses[0].expanded, false);
social.toggleHypothesis({ currentTarget: { dataset: { index: -1 } } });
const socialMarkup = readFileSync("miniapp/pages/social-profile/index.wxml", "utf8");
assert.ok(socialMarkup.indexOf('class="group hypotheses featured"') < socialMarkup.indexOf('wx:if="{{showReportDetails}}"'), "important hypotheses must not be gated by report details");
assert.ok(socialMarkup.indexOf('{{item.possibility}}') < socialMarkup.indexOf('wx:if="{{item.expanded}}"'), "the hypothesis itself stays visible");
assert.equal((socialMarkup.match(/\{\{item.possibility\}\}/g) || []).length, 1);
const reportMarkup = readFileSync("miniapp/pages/report/index.wxml", "utf8");
assert.ok(reportMarkup.indexOf('class="verdict-block intent-highlight"') < reportMarkup.indexOf('wx:if="{{showEvidence}}"'));
assert.match(socialMarkup, /查看依据与其他解释/);
console.log("PASS: hypotheses visible before disclosure, per-item evidence toggle and no duplicate inference blocks");
page.data.actionCards = [{ reportId: "a", sourceSummary: "原判断甲" }, { reportId: "b", sourceSummary: "原判断乙" }];
page.data.showAllActions = false;
page.toggleActionSource({ currentTarget: { dataset: { reportId: "a" } } });
assert.equal(page.data.visibleActionCards.length, 1);
assert.equal(page.data.visibleActionCards[0].sourceExpanded, true);
assert.equal(page.data.actionCards[1].sourceExpanded, undefined);
page.toggleActionSource({ currentTarget: { dataset: { reportId: "a" } } });
assert.equal(page.data.visibleActionCards[0].sourceExpanded, false);
assert.equal(page.data.visibleActionCards[0].sourceSummary, "原判断甲");
console.log("PASS: per-advice source disclosure preserves compact overview and original summary");
