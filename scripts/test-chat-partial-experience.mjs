import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
let definition;
new Function('Page', 'require', 'wx', readFileSync('miniapp/pages/quick/index.js', 'utf8'))(value => { definition = value; }, () => ({}), {});
let updates = 0;
const page = { ...definition, data: structuredClone(definition.data), setData(update) { Object.assign(this.data, update); updates++; } };
const first = { id: 'first', lines: [{ id: 'one', speaker: 'other', text: '【表情包文字】我想你了' }], annotations: [{ lineId: 'one', note: '通过表情包表达想念' }], decision: { possibleIntent: '可能在表达亲近' } };
const second = { id: 'second', lines: [{ id: 'two', speaker: 'self', text: '我也想你' }], annotations: [], decision: {} };
page.setData({ busy: true, imageCount: 2 });
page.jobStatus({ taskId: 'task-a', status: 'running', completedCount: 1, imageCount: 2, partialResult: { entries: [first] } });
assert.equal(page.data.partialCount, 1);
assert.equal(page.data.partialTotal, 2);
assert.equal(page.data.partialReports[0].lines[0].who, '对方');
assert.equal(page.data.partialReports[0].lines[0].note, '通过表情包表达想念');
assert.equal(page.data.busy, true, 'partial text must not settle the task');
assert.equal(page.data.result.reportId, '', 'partial is not a final cross-image report');
const oldReports = page.data.partialReports;
page.jobStatus({ taskId: 'task-a', status: 'running', completedCount: 1, imageCount: 2, partialResult: { entries: [first] } });
assert.equal(page.data.partialReports, oldReports, 'polling must not rebuild already visible cards');
page.jobStatus({ taskId: 'task-a', status: 'queued', completedCount: 2, imageCount: 2, partialResult: { entries: [first, second] } });
assert.equal(page.data.partialCount, 2);
assert.equal(page.data.partialReports[1].lines[0].who, '我');
page.jobStatus({ taskId: 'task-b', status: 'running', imageCount: 1 });
assert.equal(page.data.partialCount, 0, 'another task clears old private content');
page.jobStatus({ taskId: 'task-b', status: 'running', imageCount: 1, partialResult: { entries: [first] } });
page.jobStatus({ taskId: 'task-b', status: 'error', failureStatus: 403 });
assert.equal(page.data.partialCount, 0, 'terminal or authorization failure must not claim processing continues');
page.jobStatus({ taskId: 'task-b', status: 'running', imageCount: 1, partialResult: { entries: [first] } });
page.reset();
assert.equal(page.data.partialCount, 0);
const markup = readFileSync('miniapp/pages/quick/index.wxml', 'utf8');
assert.match(markup, /partialCount && !result.reportId/);
assert.match(markup, /后面的截图继续处理中/);
assert.match(markup, /完整判断和回复建议会在整组完成后汇总/);
assert.match(markup, /wx:for="{{part.lines}}"/);
assert.doesNotMatch(markup.slice(markup.indexOf('class="partial-results"'), markup.indexOf('wx:if="{{!result.reportId')), /openFollowup|personalize|复制/);
console.log('chat partial experience: PASS (first result before final, speaker preserved, append/dedupe, task isolation)');
