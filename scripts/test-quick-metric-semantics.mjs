const after={subjectId:'a',reportId:'new',eventStart:'2026-09-05',eventEnd:'2026-09-05',score:60,connectPrevious:true,previousReportId:'old'};
assert.equal(trend([after,before],'a').trendDelta,20);
assert.equal(trend([after,before],'a','old').trendDelta,null,'older report must not show future progress');
assert.equal(trend([after,before],'a','new').trendDelta,20);
assert.equal(trend([after,before],'a','missing').trendDelta,null,'unarchived report must not borrow another report trend');
assert.equal(trend([before,after],'b').trendDelta,null);
for(const change of [{connectPrevious:false},{eventStart:''},{eventStart:'2026-09-01'},{eventStart:'2026-02-30'},{eventEnd:'2026-99-99'},{score:null},{score:NaN},{previousReportId:'missing'}]) assert.equal(trend([before,{...after,...change}],'a').trendDelta,null);
