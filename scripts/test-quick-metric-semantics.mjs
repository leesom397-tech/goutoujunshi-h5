import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const source=readFileSync('miniapp/pages/quick/index.js','utf8');
const metrics=new Function('require','Page','wx',source+';return relationshipMetrics;')(()=>({}),()=>{},{});
const rows=(...texts)=>texts.map((text,index)=>({id:String(index),speaker:index%2?'self':'other',text}));
const empty=metrics([],[],null);
assert.equal(empty.activeRate,null,'no observed other turn is not zero interest');
const two=metrics(rows('周日有空吗？','这周不方便'),[],null);
assert.equal(two.trend,'待对照历史','one cropped conversation cannot determine a long-term trend');
assert.equal(two.trendDelta,null);
const recap=metrics(rows('明天一起见面吧','上次见到你很开心'),[],null);
assert.equal(recap.inviteFulfillment,null,'past recap cannot fulfill tomorrow invitation');
const low=metrics(rows('今天不想吃火锅，换一家？','好'),[{lineId:'0',intent:[{key:'refuse',probability:.01}]}],null);
assert.notEqual(low.stage,'明确退出信号','rejecting food or low-weight alternatives is not relationship rejection');
const duplicated=rows('你周末有空吗？','我看看安排');
assert.deepEqual(metrics([...duplicated,...duplicated],[],null),metrics(duplicated,[],null),'same line identities across screenshots are counted once');
console.log('PASS: no half-chat trend, no unlinked fulfillment, missing observations unscored, bounded meaning and repeated-line dedup');
