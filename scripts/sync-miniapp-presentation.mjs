import {readFile,writeFile} from "node:fs/promises";
import ts from "typescript";
const check=process.argv.includes("--check");
for(const name of ["personal-context","relationship-risk","risk-aware-presentation"]){
  const source=await readFile(new URL(`../lib/${name}.ts`,import.meta.url),"utf8");
  const output="// Generated by scripts/sync-miniapp-presentation.mjs; edit the shared TypeScript source.\n"+ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
  const path=new URL(`../miniapp/lib/${name}.js`,import.meta.url);
  if(check){if(await readFile(path,"utf8")!==output)throw Error(`Outdated miniapp helper: ${name}`);}
  else await writeFile(path,output);
}
console.log(check?"PASS shared miniapp helpers match TypeScript sources":"Synced shared personal context and risk helpers");
