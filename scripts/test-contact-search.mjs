import assert from "node:assert/strict";
import {build} from "esbuild";
const bundle=await build({entryPoints:["lib/capture-contact-search.ts"],bundle:true,platform:"node",format:"esm",write:false});
const {createContactSearchQueue,parseContactSearchPage}=await import("data:text/javascript;base64,"+Buffer.from(bundle.outputFiles[0].text).toString("base64"));
const runs=[],settlers=[];
const queue=createContactSearchQueue((input,signal)=>new Promise((resolve,reject)=>{
  runs.push(input);settlers.push({resolve,reject,signal});
  signal.addEventListener("abort",()=>reject(new DOMException("Aborted","AbortError")),{once:true});
}));
const a=new AbortController(),b=new AbortController(),c=new AbortController();
const first=queue.search("owner:session1","A",a.signal).catch(e=>e.name);
a.abort();
const second=queue.search("owner:session1","Au",b.signal).catch(e=>e.name);
b.abort();
const third=queue.search("owner:session1","Aud",c.signal);
assert.deepEqual(runs,["A"],"typing never starts concurrent directory preparation");
assert.equal(await second,"AbortError","superseded queued keyword settles");
settlers[0].resolve("stale");
assert.equal(await first,"AbortError","old results never replace the latest keyword");
await new Promise(r=>setImmediate(r));
assert.deepEqual(runs,["A","Aud"],"only latest queued keyword reaches helper");
settlers[1].resolve("Audrey");
assert.equal(await third,"Audrey");
await new Promise(r=>setImmediate(r));
const old=queue.search("owner:session1","old account",new AbortController().signal).catch(e=>e.name);
const next=queue.search("owner2:session2","new account",new AbortController().signal);
assert.equal(await old,"AbortError");
await new Promise(r=>setImmediate(r));
assert.equal(settlers[2].signal.aborted,true,"account/session change aborts old request");
assert.equal(runs.at(-1),"new account");
settlers[3].resolve("verified new account");assert.equal(await next,"verified new account");
const page=parseContactSearchPage({accountKey:"account",contacts:[{contactId:"a",label:"Audrey"}],hasMore:true,nextOffset:20});
assert.equal(page.nextOffset,20);assert.equal(page.contacts[0].accountKey,"account");
assert.equal(parseContactSearchPage({accountKey:"account",contacts:[],hasMore:true}).nextOffset,null,"old helper cannot fake pagination");
assert.equal(parseContactSearchPage({accountKey:"account",contacts:[],hasMore:true,nextOffset:20},20).nextOffset,null,"repeated cursor is rejected");
assert.throws(()=>parseContactSearchPage({contacts:[{contactId:"a",label:"Audrey"}]}),/账号/);
queue.reset();
console.log("PASS contact search: latest keyword only, single flight, account/session isolation, old-helper pagination fallback and forward-only pages.");
