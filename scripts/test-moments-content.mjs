import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const mod={exports:{}};
new Function('module',readFileSync('miniapp/lib/moments-content.js','utf8'))(mod);
const {momentsContent}=mod.exports;
assert.equal(readFileSync('lib/moments-content.ts','utf8').replace(/\r\n/g,'\n').split('\n').slice(2).join('\n'),readFileSync('miniapp/lib/moments-content.js','utf8').replace(/\r\n/g,'\n').replace('module.exports={momentsContent};','export {momentsContent};'),'web and miniapp projection must match');
const row=(id,source,observation,extra={})=>({libraryId:'a',mediaId:id,sourceId:source,kind:'moments',observation,...extra});
const original={mediaEvidence:[row('1','p1','对镜自拍。办公室项目工作。',{selfieCount:2}),row('2','p1','自拍画面',{selfieCount:3}),row('2','p1','自拍画面'),row('3','p2','工作拍摄现场。'),row('4','p3','没有自拍。无法判断职业。'),row('5','cover','自拍',{materialRole:'moments-cover'}),row('6','p4','旅行风景',{kind:'chat'})]};
const before=JSON.stringify(original),result=momentsContent(original);
assert.equal(result.selfieMinimum,3,'overlapping frames use max');
assert.equal(result.selfiePosts,1);
assert.equal(result.posts,3,'exclude cover and chat, dedupe frames');
assert.equal(result.groups.find(x=>x.label==='工作').count,2);
assert.equal(result.groups.find(x=>x.label==='自拍').count,1,'negation is not affirmative');
assert.equal(result.hypotheses.length,1);
assert.equal(JSON.stringify(original),before,'opening old reports does not mutate saved analysis');
assert.equal(momentsContent({}).posts,0);
assert.equal(momentsContent({mediaEvidence:[row('x','p','九宫格模糊，无法确认自拍')]}).selfieMinimum,0);
assert.equal(momentsContent({mediaEvidence:[row('x','p','图片',{contentTags:['宠物'],selfieCount:null})]}).groups[0].label,'宠物');
console.log('Moments projection: dedupe, bounds, negation, legacy, immutable passed');

assert.equal(momentsContent({mediaEvidence:[row('r','p','外卖骑手骑行配送画面')]}).groups.some(x=>x.label==='运动'),false);
