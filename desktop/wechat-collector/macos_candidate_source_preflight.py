"""Standard-library entrypoint: verify private history dependencies before quit.

Does not inspect apps, processes, account paths, permissions, keys or databases.
All codec checks use generated bytes and an in-memory SQLite connection.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib
import importlib.metadata
import io
import json
from pathlib import Path
import platform
import re
import sys


DEPENDENCIES = {
    "apsw": ("3.54.0.0", "apsw"),
    "cryptography": ("50.0.2", "cryptography.hazmat.primitives.ciphers"),
    "psutil": ("7.2.2", "psutil"),
    "cffi": ("2.1.1", "_cffi_backend"),
    "pycparser": ("3.12", "pycparser"),
    "zstandard": ("0.25.0", "zstandard"),
    "Pillow": ("12.3.0", "PIL.Image"),
}
RUNTIME_MODULES = (
    "macos_candidate_source", "macos_candidate_database_probe", "macos_candidate_device_runtime",
    "macos_candidate_prepare", "macos_candidate_probe", "macos_candidate_runtime",
    "macos_official_client_smoke", "local_database_source", "sqlcipher_primitives",
    "background_reader", "local_chat_images", "local_image_codec",
)


def check_dependencies(*, require_mac=True, profile="private-probe"):
    result = {"mode": "macos-270135-source-dependency-preflight", "ok": False,
              "accountDataRead": False, "processesInspected": False, "appsStarted": False,
              "keyWritten": False, "contentIncluded": False, "captureCompatibilityValidated": False}
    if profile not in ("private-probe", "desktop"):
        return {**result, "reason": "dependency-profile-rejected"}
    result["dependencyProfile"] = profile
    if require_mac and (sys.platform != "darwin" or platform.machine() != "arm64"
                        or platform.python_implementation() != "CPython" or sys.version_info[:2] != (3, 12)):
        return {**result, "reason": "apple-silicon-cpython312-required"}
    dependencies = []
    for name, (expected, module) in DEPENDENCIES.items():
        if name == "pycparser" and profile == "desktop": expected = "3.11"
        item = {"name": name, "expected": expected, "ready": False}
        try:
            installed = importlib.metadata.version(name)
        except importlib.metadata.PackageNotFoundError:
            installed = "missing"
        # Distributions can supply arbitrary metadata; never echo an unchecked
        # version string as a diagnostic path or secret.
        item["installed"] = installed if re.fullmatch(r"[0-9A-Za-z.+-]{1,40}", installed) else "invalid"
        if installed == expected:
            try:
                importlib.import_module(module)
                item["ready"] = True
            except Exception:
                item["reason"] = "dependency-import-failed"
        else:
            item["reason"] = "dependency-missing" if installed == "missing" else "dependency-version-mismatch"
        dependencies.append(item)
    result["dependencies"] = dependencies
    if not all(item["ready"] for item in dependencies):
        return {**result, "reason": "history-dependencies-unavailable"}
    try:
        for module in RUNTIME_MODULES:
            importlib.import_module(module)
        import apsw
        import zstandard
        from PIL import Image
        from background_reader import _decode_text
        from local_chat_images import _preview
        synthetic = "dependency preflight 合成文本"
        if _decode_text(zstandard.ZstdCompressor().compress(synthetic.encode())) != synthetic:
            return {**result, "reason": "compressed-text-preflight-failed"}
        with Image.new("RGB", (2, 2), "white") as image:
            buffer = io.BytesIO()
            image.save(buffer, format="PNG")
        preview, state = _preview(buffer.getvalue())
        if state != "preview" or not preview or preview["mime"] != "image/jpeg":
            return {**result, "reason": "image-codec-preflight-failed"}
        conn = apsw.Connection(":memory:")
        try:
            if list(conn.execute("SELECT 1")) != [(1,)]:
                return {**result, "reason": "sqlite-preflight-failed"}
        finally:
            conn.close()
    except Exception:
        return {**result, "reason": "history-runtime-preflight-failed"}
    return {**result, "ok": True, "compressedTextValidated": True, "imageCodecsValidated": True,
            "sqliteValidated": True, "runtimeImportsValidated": True, "dependenciesVerified": True}


def verify_manifest(path):
    """Package files only. Paths must stay directly within the named package."""
    path = Path(path).resolve()
    root = path.parent
    manifest = json.loads(path.read_text("utf-8"))
    files = manifest.get("files")
    if not isinstance(files, dict) or not 1 <= len(files) <= 128:
        return False
    for relative, digest in files.items():
        if (not isinstance(relative, str) or not relative or "\\" in relative
                or Path(relative).is_absolute() or ".." in Path(relative).parts
                or not isinstance(digest, str) or not re.fullmatch(r"[a-f0-9]{64}", digest)):
            return False
        target = root / relative
        if target.is_symlink() or target.resolve() != target or not target.is_file():
            return False
        if hashlib.sha256(target.read_bytes()).hexdigest() != digest:
            return False
    return True


class _PrivateParser(argparse.ArgumentParser):
    def error(self, message):
        raise ValueError("preflight-arguments-rejected")


def main():
    sys.dont_write_bytecode = True
    parser = _PrivateParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, required=True)
    args = parser.parse_args()
    if not verify_manifest(args.manifest):
        return {"ok": False, "reason": "package-integrity-rejected", "accountDataRead": False,
                "processesInspected": False, "appsStarted": False}
    return {**check_dependencies(), "packageIntegrityVerified": True}


if __name__ == "__main__":
    try:
        output = main()
    except Exception:
        output = {"ok": False, "reason": "preflight-rejected", "accountDataRead": False,
                  "processesInspected": False, "appsStarted": False}
    print(json.dumps(output, ensure_ascii=True, separators=(",", ":")))
    raise SystemExit(0 if output.get("ok") else 1)
